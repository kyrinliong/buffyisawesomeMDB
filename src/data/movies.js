export function getBoxOfficeMovies() {
  return movies.filter((m) => m.boxOffice).sort((a, b) => b.rank ? 0 : 1);
}

export function getComingSoonMovies() {
  return movies.filter((m) => m.isComingSoon);
}

export function getFanFavorites() {
  return movies.filter((m) => m.starRating >= 7.5).slice(0, 8);
}

export function getFeaturedMovies() {
  return movies.filter((m) => m.rank && m.rank <= 6).slice(0, 2);
}

export function getInTheaters() {
  return movies.filter((m) => m.boxOffice).slice(0, 6);
}

export function getStreamingMovies(serviceName) {
  const service = streamingServices.find((s) => s.name === serviceName);
  if (!service) return [];
  return movies.filter((m) => service.movies.includes(m.id));
}
